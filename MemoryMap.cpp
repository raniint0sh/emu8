#include "MemoryMap.h"
#include <cstdint>


MemoryMap::MemoryMap(){
    for(int i=0; i < 0xFFF; i++){
        MEMORY.byteBlock[i] = 0x0000;
    }
    for(int i=0; i < 16; i++){
        V[i] = 0;
        stack[i] = 0;
    }
    I = 0;
    PC = 0;
    SP = 0;
    DT = 0;
    ST = 0;
    LoadFonts();

}

MemoryMap::~MemoryMap(){

}

uint16_t MemoryMap::ReadInstruction(uint16_t addr){
    uint16_t result = 0;
    result = MEMORY.byteBlock[addr] << 8;
    result = result + MEMORY.byteBlock[addr + 1];
    PC = PC + 2;
return result;
}

void MemoryMap::LoadFonts(){

    uint8_t fontList[80] =
        {
0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
0x20, 0x60, 0x20, 0x20, 0x70, // 1
0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
0x90, 0x90, 0xF0, 0x10, 0x10, // 4
0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
0xF0, 0x10, 0x20, 0x40, 0x40, // 7
0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
0xF0, 0x90, 0xF0, 0x90, 0x90, // A
0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
0xF0, 0x80, 0x80, 0x80, 0xF0, // C
0xE0, 0x90, 0x90, 0x90, 0xE0, // D
0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
0xF0, 0x80, 0xF0, 0x80, 0x80  // F
        };

    int j = 0;
    for(int i = 0x050; i < 80; i++){
        MEMORY.byteBlock[i] = fontList[j];
        j++;
    }

}
